"""SUPPLEMENT_v1.md for PREPRINT_v1: written sections plus tables generated from locked files (no hand-copied number).
Inputs: `thirdfly_v1/C_tests.json`, `C_tables.md` (LOCK_thirdfly_v1), `posthoc_v6/H_posthoc.json` (LOCK_posthoc_v6), `gates_v6/` (prereg and
third-fly locks), `labels_audit_v1/ERROR_RATES.json`, `labels_audit_v1/RESCORE_exploratory.json` (LOCK_replication_v1),
`results/run2/P.json` (tag ledger-scorecard-v1). Output: `paper/SUPPLEMENT_v1.md`.

    uv run --project ledger --no-sync python ledger/scripts/posthoc/supplement_v1.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from brainir_ledger import RESEARCH  # noqa: E402


def f(x, n=2):
    return "-" if x is None else (f"{x:.{n}f}" if isinstance(x, (int, float)) else str(x))


def j(rel):
    return json.loads((RESEARCH / rel).read_text())


NAME_MAP = [
    ("first animal, MANC", "MANC v1.2.1 front-leg network (our rebuild, identical to the authors')", "`networks.front_leg()`"),
    ("second animal, MaleCNS", "the authors' MaleCNS front-leg network (`W_20260210_vncRoisOnly`)", "`arms.malecns_network()`"),
    ("third animal, BANC", "the authors' BANC front-leg network as released (`W_20260217.npz`)", "`banc.network()`"),
    ("the authors' single-neuron screen", "their 128-replicate screen of single descending neurons", "A0"),
    ("the authors' whole-type list", "their 16-replicate screen of whole cell types", "A1"),
    ("our current-setting procedure", "tuner v2, one free setting (required active front-leg motor neurons) = 1", "tuner v2, K = 1; B1r / B2r / BT"),
    ("the original procedure", "the same without the motor-neuron requirement", "K = 0; B1-lo10 / B2"),
    ("the current sweep", "19 fixed currents 4-2,048, best in-bounds score", "rulebook v4 fix 1; dx-1 / ms / bs"),
    ("one-sided screens", "one side's copies stimulated, that side's motor neurons read out", "half-fly screens; BH"),
    ("copies with redrawn synapse counts", "Poisson copies of the network", "B4.2 / C2; BN"),
    ("our previous analysis' stability test", "stability under count noise in MANC (run 5)", "Part S"),
    ("the first literature test", "front-leg rhythm when a type is switched on (39 types)", "exam 1"),
    ("the second literature test", "movement phenotypes of 27 hemilineages", "exam 2"),
    ("types excluded because their outcomes were known", "the exposed set", "exposed"),
    ("the procedure's one free setting", "required active front-leg motor neurons", "K"),
    ("the rules", "the pre-registration rulebooks", "PREREG v1-v6"),
]


def main() -> None:
    C = j("thirdfly_v1/C_tests.json")
    H = j("posthoc_v6/H_posthoc.json")
    gate = j("gates_v6/BANC_GATE.json")
    er = j("labels_audit_v1/ERROR_RATES.json")
    rs = j("labels_audit_v1/RESCORE_exploratory.json")
    L = ["# Supplement to: How reproducible is a simulated screen's hit list? A walking screen tested across three fly connectomes", "",
         "Every number here comes from a locked file of the BrainIR prediction ledger (branch `ledger/v1`); this file is generated by",
         "`ledger/scripts/posthoc/supplement_v1.py`. \"Post hoc\" marks analyses of the first two animals, which were seen before the rules for",
         "this analysis were written.", "", "## S1. Names used in the ledger", "", "| In the paper | What it is | In the ledger's files |", "|---|---|---|"]
    L += [f"| {a} | {b} | {c} |" for a, b, c in NAME_MAP]
    # S2 build and gate
    g = gate["conditions"]
    sd = C["B2_sides"]
    L += ["", "## S2. The third animal: build, gate, type matching and sides", "",
          "- **Sources.** The authors' released BANC matrix (4,963 neurons, 496,041 signed connections, no synapse threshold) and table, at the",
          "  commit pinned in the ledger, checked by SHA-256; their run configurations read from their Zenodo record.",
          "- **Build.** The matrix as released; every row single-signed, agreeing with the transmitter rule (verified, else predicted) for all",
          "  4,863 rows the rule covers; sizes from surface area; excitatory descending neurons by the authors' rule (922); read-out the 139",
          "  front-leg motor neurons (12 neck motor neurons left out, as in the other animals).",
          f"- **Gate** (written before it ran; DNg100 at the authors' current, 64 draws): intact mean {f(g['intact']['mean'], 3)} "
          f"({f(g['intact']['frac_ge_0_5'])} of draws >= 0.5; authors 0.984); E1 silenced {f(g['E1']['mean'], 3)}; E2 silenced "
          f"{f(g['E2']['mean'], 3)}; I2 silenced {f(g['I2']['mean'], 3)} (authors 0.014, 0.035, 0.993). Verdict: {gate['verdict']}.",
          "- **Type matching.** 1,221 of 1,313 descending neurons carry a MANC match ID; 860 excitatory ones map to 309 MANC types; high",
          "  confidence 206, medium 103, low 0. The three-animal set: 182 types (181 without DNg100).",
          f"- **Sides.** BANC's annotated sides agree with each neuron's output side for {f(sd['agreement'] * 100, 1)} % of {sd['n_defined']} "
          f"neurons (bar 90 %), so output sides are used; {sd['n_all_matched']} types have copies on both sides, {sd['n_label_consistent']} of "
          "them with a single BANC label (the set of the left-right test)."]
    # S3 the tests
    tab = (RESEARCH / "thirdfly_v1" / "C_tables.md").read_text()
    body = tab.split("## The tests (words are PREREG v6's; sets without DNg100)")[1].split("## Part V")[0]
    L += ["", "## S3. Every pre-registered test of the third animal (words fixed in advance; DNg100 left out)", "",
          f"Validity: our current-setting procedure gave DNg100 >= 0.5 in {C['B4_validity']['tuned']['dng100_seeds_ge_0_5']} of 16 draws (bar 12),",
          f"the sweep in {C['B4_validity']['sweep']['dng100_seeds_ge_0_5']} of 8 (bar 6), so the sweep is primary for the cross-animal tests.",
          "Set names: `three_animal` = the 182 types matched with high confidence in all three animals; `manc_banc_high` / `mcns_banc_high` = types",
          "matched with high confidence between MANC (or MaleCNS) and BANC; `_noDNg100` = DNg100 left out; CP = exact (Clopper-Pearson) interval;",
          "OC ratio = overlap relative to the within-animal overlap; rho_x = cross-half agreement before division by the ceiling.", "",
          body.strip(), "",
          "Departures from the run's instructions, each with its reason, are listed in the rulebook (`PREREG_v6.md`, Part D): the BANC table the",
          "authors' configuration names; the 139 front-leg motor neurons; a label-consistent set for the left-right test; the cross-half form of",
          "the count-noise test (BANC has no bilateral group annotation for paired draws); exact intervals for shares; words on the sets",
          "without DNg100; the pooling test on the third animal as the only target (the instructions' average is positive by construction);",
          "12 types for the stability test; 2-s runs for the DNb08 check; the MANC sweep's stored results; a wiring check with a fixed caveat;",
          "a same-name subset; the DNg100 prediction judged even when neither BANC screen is valid; campaigns split into parts."]
    # S4 exam 1
    P = j("results/run2/P.json")["primary"]["result"]
    L += ["", "## S4. The first literature test in detail", "",
          f"- **What it asked.** Whether the authors' whole-type score ranks types that drive rhythmic front-leg movement when switched on in flies "
          f"above types that do not. 39 labelled types ({P['n_pos']} yes, {P['n_neg']} no), labels frozen before scoring.",
          f"- **Verdict (locked).** Area under the curve {f(P['auroc'], 3)} ({f(P['boot']['lo'], 3)}-{f(P['boot']['hi'], 3)}): not better than chance "
          f"by the pre-registered rule. The best wiring baseline, picked on these labels, counted signed two-step paths "
          f"({f(P['baselines_auroc']['S2_twohop_signed'], 3)}).",
          f"- **Why we do not interpret it.** All {er['census_39']['atlas_only']['n']} types whose labels rest on one optogenetic atlas of intact,",
          "  freely walking flies are \"yes\"; the \"no\" labels come from other kinds of experiment (takeoff, flight), so a type's label is",
          "  confounded with its source. Most labels describe intact flies, whereas the model is of the nerve cord alone.",
          f"- **Audit.** Fresh readers re-read every source: {er['census_39']['all']['errors']} errors among the 39 types "
          f"({f(er['census_39']['all']['rate'] * 100, 1)} %), {er['census_39']['atlas_only']['errors']} among the atlas types and "
          f"{er['census_39']['other']['errors']} among the {er['census_39']['other']['n']} others; below the pre-registered 10 %, so the test "
          "stands, with an erratum for six types excluded because their outcomes were known (DNg100's label corrected to yes).",
          f"- **Re-scored with audited labels (exploratory, once).** Simulation {f(rs['audited']['auroc'], 3)}; two-step counting "
          f"{f(rs['audited']['baselines_auroc']['S2_twohop_signed'], 3)}."]
    # S5 Part H
    L += ["", "## S5. The first two animals' hit lists by threshold (POST HOC)", "",
          "High-confidence types without DNg100 (214). k = hits in both; chance = expected k; p = hypergeometric; ratio = overlap relative to",
          "the within-animal overlap (95 % interval).", "", "| procedure | threshold | MANC hits | MaleCNS hits | k | chance | p | ratio |",
          "|---|---|---|---|---|---|---|---|"]
    names = {"tuned_B1r_x_B2r": "current-setting", "authors_A1_x_B2r": "authors' list vs ours", "original_K0_B1lo10_x_B2": "original",
             "sweep_dx1_x_ms": "current sweep"}
    for pair, lab in names.items():
        b = H["pairs"][pair]["high|without_DNg100"]
        for z in ("0.3", "0.4", "0.5", "0.6"):
            o = b["cuts"][z]["overlap"]
            p, bo = o["point"], o["bootstrap_95"]["OC_ratio"]
            pv = "<0.001" if p["hypergeom_p"] < 0.001 else f(p["hypergeom_p"], 3)
            L.append(f"| {lab} | {z} | {p['n_x']} | {p['n_y']} | {p['k']} | {f(p['chance_expectation'])} | {pv} | "
                     f"{f(p['OC_ratio'])} ({f(bo['lo'])}-{f(bo['hi'])}) |")
    L += ["", "Whole-ranking agreement (fraction of the ceiling, 214 types): " + "; ".join(
        f"{names[pr]} {f(H['pairs'][pr]['high|without_DNg100']['agreement']['primary']['ratio'])}" for pr in names) + " (post hoc)."]
    # S6 Part V
    V = C["V"]["V2"]["table"]
    L += ["", "## S6. Single DNb08 neurons in our MaleCNS model (fixed currents, 2-s runs, 16 draws)", "",
          "| current | " + " | ".join(f"position {p}" for p in sorted(V, key=int)) + " |", "|---|" + "---|" * len(V)]
    curs = sorted({c for p in V.values() for c in p}, key=float)
    for c in curs:
        L.append(f"| {c} | " + " | ".join(f"{f(V[p][c]['frac_ge_0_5'])} (mean {f(V[p][c]['mean'])})" if c in V[p] else "-"
                                         for p in sorted(V, key=int)) + " |")
    L += ["", f"DNg100 at the authors' MaleCNS configuration: {C['V']['V1']['words']} (mean {f(C['V']['V1']['mean'], 3)})."]
    # S7 forward list
    L += ["", "## S7. The twelve experiments, with the third animal's scores (readings unchanged)", "",
          "| type | group | readings: replication / authors' list / counting | BANC score (current-setting) | BANC score (sweep) | BANC match |",
          "|---|---|---|---|---|---|"]
    for r in C["F"]:
        rd = f"{r.get('replication_reading', '-')} / {r.get('single_connectome_reading', '-')} / {r.get('counting_reading', '-')}"
        L.append(f"| {r['manc_type']} | {r.get('group', r.get('category', '-'))} | {rd} | {f(r['banc_tuned'])} | {f(r['banc_sweep'])} | {r['banc_match']} |")
    # S8 compute
    d1, d2 = j("gates_v6/DETERMINISM_v6_stage1.json"), j("gates_v6/DETERMINISM_v6_stage2.json")
    tg = j("gates_v6/TRUST_GATE_v6.json")
    L += ["", "## S8. Compute, determinism and review", "",
          f"- Trust gate: {tg['identical']} of {tg['n']} previously locked simulations reproduced exactly on GitHub Actions.",
          f"- Determinism re-runs: {d1['identical']} of {d1['n']} and {d2['identical']} of {d2['n']} identical.",
          "- The rules of this analysis were audited by a newly started agent session (14 findings, all applied) and re-checked by the same",
          "  session; the audit, its re-check and the resolution are in `reviews_v6/`.", ""]
    (RESEARCH / "paper" / "SUPPLEMENT_v1.md").write_text("\n".join(L) + "\n")
    print("wrote SUPPLEMENT_v1.md", len(L), "lines")


if __name__ == "__main__":
    main()
